    @pytest.mark.asyncio
    async def test_서비스목록_페이징(self, 테스트_세션, 여러_서비스_데이터):
        """서비스 목록 페이징 테스트"""
        async with 테스트_세션() as 세션:
            서비스관리 = 서비스관리서비스(세션)
            
            # 여러 서비스 생성
            for 서비스데이터 in 여러_서비스_데이터:
                생성요청 = 서비스생성요청(**서비스데이터)
                await 서비스관리.서비스생성(생성요청)
            
